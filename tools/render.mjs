#!/usr/bin/env node
/**
 * 结构化用例 JSON -> Playwright spec.ts
 *
 * 设计约束（别改）：
 *   1. 用例里不允许出现 CSS/XPath 选择器，只允许语义 target。
 *   2. 期望值只能来自需求/接口契约，模型不许“发明”期望。
 *   3. 生成物是给人评审、给 CI 跑的资产，不是一次性脚本。
 *
 * 用法：
 *   node tools/render.mjs spec/cases/order-001.json
 *   node tools/render.mjs --all spec/cases
 */
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'

const q = (v) => JSON.stringify(v)

function locatorExpr(t) {
  if (!t || typeof t !== 'object' || Array.isArray(t)) throw new Error('target 必须是对象')
  if (t.testid) return `page.getByTestId(${q(t.testid)})`
  if (t.role) return `page.getByRole(${q(t.role)}${t.name ? `, { name: ${q(t.name)} }` : ''})`
  if (t.label) return `page.getByLabel(${q(t.label)})`
  if (t.placeholder) return `page.getByPlaceholder(${q(t.placeholder)})`
  if (t.text) return `page.getByText(${q(t.text)})`
  throw new Error(`无法解析 target：${q(t)}`)
}

function renderStep(s, ctx) {
  const L = (x) => `    ${x}`
  switch (s.action) {
    case 'goto':
      return [L(`await page.goto(${q(s.url)})`)]
    case 'click':
      return [L(`await ${locatorExpr(s.target)}.click(${s.force ? '{ force: true }' : ''})`)]
    case 'fill':
      return [L(`await ${locatorExpr(s.target)}.fill(${q(s.value)})`)]
    case 'select':
      return [L(`await ${locatorExpr(s.target)}.selectOption(${q(s.value)})`)]
    case 'check':
      return [L(`await ${locatorExpr(s.target)}.check()`)]
    case 'press':
      return [L(s.target ? `await ${locatorExpr(s.target)}.press(${q(s.key)})` : `await page.keyboard.press(${q(s.key)})`)]
    case 'waitFor':
      return [L(`await ${locatorExpr(s.target)}.waitFor({ state: ${q(s.state ?? 'visible')} })`)]
    case 'captureNetwork': {
      ctx.net += 1
      ctx.names.set(s.name ?? `net_${ctx.net}`, `net_${ctx.net}`)
      return [L(`const net_${ctx.net} = page.waitForResponse((r) => r.url().includes(${q(s.urlContains)}))`)]
    }
    case 'expectNetwork': {
      const v = ctx.names.get(s.name) ?? s.name
      const lines = [L(`expect((await ${v}).status()).toBe(${s.status ?? 200})`)]
      if (s.jsonPath !== undefined && s.equals !== undefined) {
        lines.push(L(`expect((await ${v}).json()).toMatchObject(${JSON.stringify(s.equals, null, 2).replace(/\n/g, '\n    ')})`))
      }
      return lines
    }
    case 'expectUrl':
      return [L(`await expect(page).toHaveURL(${s.contains ? `/${String(s.contains).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}/` : q(s.equals)})`)]
    case 'expect': {
      const loc = locatorExpr(s.target)
      const a = s.assertion ?? {}
      switch (a.type) {
        case 'visible':
          return [L(`await expect(${loc}).toBeVisible()`)]
        case 'hidden':
          return [L(`await expect(${loc}).toBeHidden()`)]
        case 'enabled':
          return [L(`await expect(${loc}).toBeEnabled()`)]
        case 'disabled':
          return [L(`await expect(${loc}).toBeDisabled()`)]
        case 'text':
          return [L(a.exact ? `await expect(${loc}).toHaveText(${q(a.value)})` : `await expect(${loc}).toContainText(${q(a.value)})`)]
        case 'value':
          return [L(`await expect(${loc}).toHaveValue(${q(a.value)})`)]
        case 'count':
          return [L(`await expect(${loc}).toHaveCount(${a.value})`)]
        default:
          throw new Error(`未支持的断言类型：${a.type}`)
      }
    }
    default:
      throw new Error(`未支持的 action：${s.action}`)
  }
}

function renderCase(c) {
  const out = []
  out.push(`// AUTO-GENERATED by tools/render.mjs —— 请勿手改；改 spec/cases/${c.id}.json 后重新生成`)
  out.push(`// case: ${c.id}  requirement: ${c.requirement ?? '-'}  priority: ${c.priority ?? '-'}`)
  out.push(`import { test, expect } from '@playwright/test'`)
  out.push('')
  out.push(`test.describe(${q(`${c.id} ${c.title}`)}, () => {`)

  const routes = c.fixtures?.routes ?? []
  if (routes.length) {
    out.push('  test.beforeEach(async ({ page }) => {')
    for (const r of routes) {
      const body =
        r.json !== undefined
          ? `{ status: ${r.status ?? 200}, contentType: 'application/json', body: JSON.stringify(${JSON.stringify(r.json)}) }`
          : `{ status: ${r.status ?? 200} }`
      out.push(`    await page.route(${q(r.url)}, (route) => route.fulfill(${body}))`)
    }
    out.push('  })')
    out.push('')
  }

  out.push(`  test(${q(c.title)}, async ({ page }) => {`)
  const ctx = { net: 0, names: new Map() }
  for (const step of c.steps) out.push(...renderStep(step, ctx))
  out.push('  })')
  out.push('})')
  return out.join('\n') + '\n'
}

const argv = process.argv.slice(2)
const checkOnly = argv.includes('--check')
let mismatches = 0

const allIdx = argv.indexOf('--all')
if (allIdx !== -1) {
  const dir = argv[allIdx + 1]
  const files = (await readdir(dir)).filter((f) => f.endsWith('.json'))
  for (const f of files) {
    const c = JSON.parse(await readFile(join(dir, f), 'utf8'))
    const target = join('tests', `${c.id}.spec.ts`)
    const content = renderCase(c)

    if (checkOnly) {
      const existing = await readFile(target, 'utf8').catch(() => null)
      if (existing === null) {
        console.log(`[check] MISSING ${target}`)
        mismatches++
      } else if (existing !== content) {
        console.log(`[check] DIRTY   ${target}（被手改过，或改了 case 没重新生成）`)
        mismatches++
      } else {
        console.log(`[check] ok      ${target}`)
      }
      continue
    }

    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, content, 'utf8')
    console.log(`[render] ${f} -> ${target} (${c.steps.length} steps)`)
  }

  if (checkOnly) {
    if (mismatches > 0) {
      console.error(`\n${mismatches} 个生成物与 spec/cases 不一致——tests/ 只能由 render 产出`)
      process.exit(1)
    }
    console.log('\n全部一致：tests/ 没有被手改')
  }
} else if (argv[0]) {
  const c = JSON.parse(await readFile(argv[0], 'utf8'))
  const target = argv[2] || join('tests', `${c.id}.spec.ts`)
  await mkdir(dirname(target), { recursive: true })
  await writeFile(target, renderCase(c), 'utf8')
  console.log(`[render] ${argv[0]} -> ${target}`)
} else {
  console.error('用法: node tools/render.mjs <case.json> [输出文件] | --all <目录>')
  process.exit(1)
}
