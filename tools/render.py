#!/usr/bin/env python
"""Compile validated case JSON to ordinary pytest + Playwright Python code."""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from tools.contracts import read_case, validate_case

GENERATED_PREFIX = "# AUTO-GENERATED by tools/render.py"
HEADER = GENERATED_PREFIX + " —— 请勿手改；改 {rel} 后重新生成"
MATCHERS = {"eq": "==", "ne": "!=", "gt": ">", "ge": ">=", "lt": "<", "le": "<="}


def q(value) -> str:
    """JSON input data must become Python literals, including nested bool/null."""
    return json.dumps(value, ensure_ascii=False) if isinstance(value, str) else repr(value)


def comment(value) -> str:
    return str(value).replace("\r", "\\r").replace("\n", "\\n")


def locator(target: dict, root: str = "page") -> str:
    if not isinstance(target, dict) or not target:
        raise ValueError(f"target 必须是对象：{target!r}")
    if "within" in target:
        root = locator(target["within"], root)
    if "testid" in target:
        return f'{root}.get_by_test_id({q(target["testid"])})'
    if "href" in target:
        href = target["href"].replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\a ").replace("\r", "\\d ")
        result = f'{root}.locator({q("a[href=" + chr(34) + href + chr(34) + "]")})'
        if "name" in target:
            named = f'{root}.get_by_role("link", name={q(target["name"])}, exact={q(target.get("exact", False))})'
            result += f".and_({named})"
        return result
    if "role" in target:
        args = [q(target["role"])]
        if "name" in target:
            args.append(f'name={q(target["name"])}')
        if "exact" in target:
            args.append(f'exact={q(target["exact"])}')
        return f'{root}.get_by_role({", ".join(args)})'
    for key, method in (("label", "get_by_label"), ("placeholder", "get_by_placeholder"), ("text", "get_by_text")):
        if key in target:
            extra = f', exact={q(target["exact"])}' if "exact" in target else ""
            return f"{root}.{method}({q(target[key])}{extra})"
    raise ValueError(f"无法解析 target：{target!r}")


def goto_url(url: str) -> str:
    return q(url) if re.match(r"^https?://", url) else f"base_url + {q(url)}"


def page_var(step: dict) -> str:
    return step["page"]


def call_expr(step: dict) -> str:
    kwargs = ", ".join(f"{k}={q(v)}" for k, v in step.get("args", {}).items())
    return f'{page_var(step)}.{step["method"]}({kwargs})'


def step_uses_page(step: dict) -> bool:
    if step["action"] in {"goto", "expectUrl", "captureNetwork", "raw", "click", "fill", "select", "check", "press", "waitFor"}:
        return True
    return step["action"] == "expect" and "target" in step


def network_var(step: dict, nets: dict[str, str]) -> str:
    if "name" in step:
        return nets[step["name"]]
    if len(nets) != 1:
        raise ValueError("expectNetwork must name an existing capture")
    return next(iter(nets.values()))


def render_step(step: dict, indent: str, nets: dict[str, str]) -> list[str]:
    action = step["action"]
    if action == "goto":
        return [f"{indent}page.goto({goto_url(step['url'])})"]
    if action == "click":
        options = f"force={q(step['force'])}" if "force" in step else ""
        return [f"{indent}{locator(step['target'])}.click({options})"]
    if action in {"fill", "select"}:
        method = "fill" if action == "fill" else "select_option"
        return [f"{indent}{locator(step['target'])}.{method}({q(step['value'])})"]
    if action == "check":
        return [f"{indent}{locator(step['target'])}.check()"]
    if action == "press":
        owner = locator(step["target"]) if "target" in step else "page.keyboard"
        return [f"{indent}{owner}.press({q(step['key'])})"]
    if action == "waitFor":
        return [f"{indent}{locator(step['target'])}.wait_for(state={q(step.get('state', 'visible'))})"]
    if action == "expectUrl":
        expected = q(step["equals"]) if "equals" in step else f"re.compile({q(re.escape(step['contains']))})"
        return [f"{indent}expect(page).to_have_url({expected})"]
    if action == "expectNetwork":
        response = network_var(step, nets) + ".value"
        lines = [f"{indent}assert {response}.status == {step.get('status', 200)}"]
        if "equals" in step:
            lines.append(f"{indent}assert {response}.json() == {q(step['equals'])}")
        return lines
    if action == "call":
        return [f"{indent}{call_expr(step)}"]
    if action == "raw":
        operation = step.get("operation", "click")
        value = q(step["value"]) if operation in {"fill", "press"} else ""
        return [
            f"{indent}# TODO(pom-gap): {comment(step['pom_gap'])}",
            f"{indent}{locator(step['target'])}.{operation}({value})",
        ]
    if action == "expect" and "page" in step:
        expr = call_expr(step)
        matcher = step.get("matcher", "eq")
        if matcher == "truthy":
            assertion = expr
        elif matcher == "contains":
            assertion = f"{q(step['value'])} in {expr}"
        else:
            assertion = f"{expr} {MATCHERS[matcher]} {q(step['value'])}"
        return [f"{indent}assert {assertion}"]
    if action == "expect":
        assertion = step["assertion"]
        kind = assertion["type"]
        methods = {
            "visible": "to_be_visible()", "hidden": "to_be_hidden()",
            "enabled": "to_be_enabled()", "disabled": "to_be_disabled()",
        }
        if kind in methods:
            call = methods[kind]
        else:
            method = {
                "text": "to_have_text" if assertion.get("exact") else "to_contain_text",
                "value": "to_have_value", "count": "to_have_count",
            }[kind]
            call = f"{method}({q(assertion['value'])})"
        return [f"{indent}expect({locator(step['target'])}).{call}"]
    raise ValueError(f"未支持的 action：{action}")


def render_case(case: dict, rel: str) -> str:
    validate_case(case)
    steps = case["steps"]
    body: list[str] = []
    nets: dict[str, str] = {}
    for route in case.get("routes", []):
        payload = json.dumps(route.get("json", {}), ensure_ascii=False, allow_nan=False)
        body.append(
            f"    page.route({q(route['url'])}, lambda route: "
            f"route.fulfill(status={route.get('status', 200)}, content_type='application/json', body={q(payload)}))"
        )
    index = 0
    while index < len(steps):
        step = steps[index]
        if step["action"] == "captureNetwork":
            name = step.get("name") or f"net_{len(nets) + 1}"
            var = f"resp_{len(nets) + 1}"
            nets[name] = var
            predicate = f"{q(step['urlContains'])} in r.url"
            if "method" in step:
                predicate += f" and r.request.method == {q(step['method'])}"
            body.append(f"    with page.expect_response(lambda r: {predicate}) as {var}:")
            body.extend(render_step(steps[index + 1], "        ", nets))
            index += 2
        else:
            body.extend(render_step(step, "    ", nets))
            index += 1

    ordered: list[str] = []
    if case.get("routes") or any(step_uses_page(s) for s in steps):
        ordered.append("page")
    if any(s["action"] == "goto" and not re.match(r"^https?://", s["url"]) for s in steps):
        ordered.append("base_url")
    for name in list(case.get("fixtures", [])) + list(case.get("pages", {})):
        if name not in ordered:
            ordered.append(name)
    typed = {"page": "page: Page", "base_url": "base_url: str"}
    signature = ", ".join(typed.get(name, name) for name in ordered)
    lines = [
        HEADER.format(rel=comment(rel)),
        f"# case: {case['id']}  requirement: {comment(case.get('requirement', '-'))}  priority: {case.get('priority', '-')}",
    ]
    if case.get("sources"):
        lines.append(f"# sources: {comment(', '.join(case['sources']))}")
    if any(s["action"] == "expectUrl" and "contains" in s for s in steps):
        lines.extend(["import re", ""])
    if "page" in ordered:
        lines.append("from playwright.sync_api import Page, expect")
    lines.extend(["", "", f"def {test_name(case['id'])}({signature}) -> None:"])
    lines.append(f"    {q(case['id'] + ' ' + case['title'])}")
    lines.extend(body)
    lines.append("")
    source = "\n".join(lines)
    compile(source, rel, "exec", dont_inherit=True)
    return source


def test_name(case_id: str) -> str:
    return "test_" + re.sub(r"[^0-9a-zA-Z]+", "_", case_id).strip("_").lower()


def source_reference(path: Path) -> str:
    try:
        return path.resolve().relative_to(Path.cwd().resolve()).as_posix()
    except ValueError:
        return path.name


def generated_files(directory: Path) -> set[Path]:
    if not directory.exists():
        return set()
    return {
        p for p in directory.rglob("test_*.py")
        if p.read_text(encoding="utf-8").startswith(GENERATED_PREFIX)
    }


def compile_plan(files: list[Path], out_dir: Path) -> dict[Path, str]:
    plan = {}
    ids = set()
    for path in files:
        case = read_case(path)
        validate_case(case)
        if case["id"] in ids:
            raise ValueError(f"duplicate case id: {case['id']}")
        ids.add(case["id"])
        target = out_dir / (test_name(case["id"]) + ".py")
        plan[target] = render_case(case, source_reference(path))
    return plan


def apply_plan(plan: dict[Path, str], *, check: bool) -> int:
    mismatches = 0
    # Refuse to overwrite any handwritten file before writing any generated file.
    for target in plan:
        if target.exists() and not target.read_text(encoding="utf-8").startswith(GENERATED_PREFIX):
            raise ValueError(f"unmanaged test file: {target}; choose a dedicated --out-dir")
    for target, source in plan.items():
        if check:
            existing = target.read_text(encoding="utf-8") if target.exists() else None
            if existing != source:
                print(f"[check] {'MISSING' if existing is None else 'DIRTY'} {target}")
                mismatches += 1
            else:
                print(f"[check] OK {target}")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(source, encoding="utf-8")
            print(f"[render] {target}")
    return 1 if mismatches else 0


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser()
    parser.add_argument("case", nargs="?")
    parser.add_argument("--all", dest="all_dir")
    parser.add_argument("--out", default="")
    parser.add_argument("--out-dir", default="tests")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if bool(args.case) == bool(args.all_dir) or (args.all_dir and args.out):
        parser.error("choose CASE [--out FILE] or --all DIR [--out-dir DIR]")
    try:
        out_dir = Path(args.out_dir)
        if args.all_dir:
            directory = Path(args.all_dir)
            if not directory.is_dir():
                raise ValueError(f"case directory does not exist: {directory}")
            files = sorted(directory.rglob("*.json"))
            if not files:
                raise ValueError(f"no case JSON files: {directory}")
            plan = compile_plan(files, out_dir)
            orphans = generated_files(out_dir) - set(plan)
            if orphans:
                for path in sorted(orphans):
                    print(f"[check] ORPHAN {path}")
                print("[render] Use the complete case directory or a dedicated --out-dir; remove obsolete generated files explicitly.")
                return 1
        else:
            path = Path(args.case)
            case = read_case(path)
            source = render_case(case, source_reference(path))
            target = Path(args.out) if args.out else out_dir / (test_name(case["id"]) + ".py")
            plan = {target: source}
        return apply_plan(plan, check=args.check)
    except (OSError, ValueError, SyntaxError) as exc:
        print(f"[render] FAIL {exc}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
