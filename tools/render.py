#!/usr/bin/env python
"""结构化用例 JSON -> pytest + Playwright(Python) 测试函数。

设计约束（别改）：
  1. 用例里不允许出现 CSS/XPath 选择器，只允许语义 target。
  2. 期望值只能来自需求/接口契约，模型不许"发明"期望。
  3. 生成物是给人评审、给 CI 跑的资产，不是一次性脚本。

用法：
    python tools/render.py spec/cases/th-001.json
    python tools/render.py --all spec/cases/testerhome
    python tools/render.py --all spec/cases --check
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HEADER = "# AUTO-GENERATED by tools/render.py —— 请勿手改；改 {rel} 后重新生成"


def q(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def locator(target: dict) -> str:
    if not isinstance(target, dict) or not target:
        raise ValueError(f"target 必须是对象：{target!r}")
    if target.get("testid"):
        return f'page.get_by_test_id({q(target["testid"])})'
    if target.get("href"):
        # 同名链接消歧：href 是链接语义的一部分，用它比用序号可靠
        selector = f'a[href="{target["href"]}"]'
        if target.get("name"):
            return f"page.locator({q(selector)}, has_text={q(target['name'])})"
        return f"page.locator({q(selector)})"
    if target.get("role"):
        args = [q(target["role"])]
        if target.get("name"):
            args.append(f"name={q(target['name'])}")
        if target.get("exact"):
            args.append("exact=True")
        return f'page.get_by_role({", ".join(args)})'
    if target.get("label"):
        extra = ", exact=True" if target.get("exact") else ""
        return f'page.get_by_label({q(target["label"])}{extra})'
    if target.get("placeholder"):
        return f'page.get_by_placeholder({q(target["placeholder"])})'
    if target.get("text"):
        return f'page.get_by_text({q(target["text"])})'
    raise ValueError(f"无法解析 target：{target!r}")


def goto_url(url: str) -> str:
    if re.match(r"^https?://", url):
        return q(url)
    return f"base_url + {q(url)}"


def render_step(step: dict, indent: str, nets: dict[str, str]) -> list[str]:
    action = step.get("action")
    pad = indent

    if action == "goto":
        return [f"{pad}page.goto({goto_url(step['url'])})"]
    if action == "click":
        return [f"{pad}{locator(step['target'])}.click()"]
    if action == "fill":
        return [f"{pad}{locator(step['target'])}.fill({q(step['value'])})"]
    if action == "select":
        return [f"{pad}{locator(step['target'])}.select_option({q(step['value'])})"]
    if action == "check":
        return [f"{pad}{locator(step['target'])}.check()"]
    if action == "press":
        if step.get("target"):
            return [f"{pad}{locator(step['target'])}.press({q(step['key'])})"]
        return [f"{pad}page.keyboard.press({q(step['key'])})"]
    if action == "waitFor":
        state = step.get("state", "visible")
        return [f'{pad}{locator(step["target"])}.wait_for(state={q(state)})']
    if action == "expectUrl":
        if step.get("equals"):
            return [f"{pad}expect(page).to_have_url({q(step['equals'])})"]
        pattern = re.escape(step["contains"])
        return [f"{pad}expect(page).to_have_url(re.compile({q(pattern)}))"]
    if action == "expectNetwork":
        var = nets.get(step.get("name", ""), "resp_1")
        return [f"{pad}assert {var}.value.status == {int(step.get('status', 200))}"]
    if action == "expect":
        target = locator(step["target"])
        assertion = step.get("assertion") or {}
        kind = assertion.get("type")
        mapping = {
            "visible": "to_be_visible()",
            "hidden": "to_be_hidden()",
            "enabled": "to_be_enabled()",
            "disabled": "to_be_disabled()",
        }
        if kind in mapping:
            return [f"{pad}expect({target}).{mapping[kind]}"]
        if kind == "text":
            method = "to_have_text" if assertion.get("exact") else "to_contain_text"
            return [f"{pad}expect({target}).{method}({q(assertion.get('value', ''))})"]
        if kind == "value":
            return [f"{pad}expect({target}).to_have_value({q(assertion.get('value', ''))})"]
        if kind == "count":
            return [f"{pad}expect({target}).to_have_count({int(assertion.get('value', 0))})"]
        raise ValueError(f"未支持的断言类型：{kind}")

    raise ValueError(f"未支持的 action：{action}")


def render_case(case: dict, rel: str) -> str:
    steps = case.get("steps") or []
    if not steps:
        raise ValueError(f"{case.get('id')}: steps 为空")

    body: list[str] = []
    nets: dict[str, str] = {}
    needs_re = False
    index = 0

    while index < len(steps):
        step = steps[index]
        action = step.get("action")

        if action == "captureNetwork":
            # Python 里网络等待是上下文管理器：把紧随其后的一步包进 with
            if index + 1 >= len(steps):
                raise ValueError(f"{case['id']}: captureNetwork 后面必须有一步真实操作")
            name = step.get("name") or f"net_{len(nets) + 1}"
            var = f"resp_{len(nets) + 1}"
            nets[name] = var
            body.append(f"    with page.expect_response(lambda r: {q(step['url_contains'])} in r.url) as {var}:")
            for line in render_step(steps[index + 1], "        ", nets):
                body.append(line)
            index += 2
            continue

        if action == "expectUrl" and step.get("contains"):
            needs_re = True

        for line in render_step(step, "    ", nets):
            body.append(line)
        index += 1

    func = "test_" + re.sub(r"[^0-9a-zA-Z]+", "_", str(case["id"])).strip("_").lower()
    title = str(case.get("title", "")).replace('"', "'")

    lines: list[str] = []
    lines.append(HEADER.format(rel=rel))
    lines.append(f"# case: {case['id']}  requirement: {case.get('requirement', '-')}  priority: {case.get('priority', '-')}")
    if needs_re:
        lines.append("import re")
        lines.append("")
    lines.append("from playwright.sync_api import Page, expect")
    lines.append("")
    lines.append("")
    lines.append(f"def {func}(page: Page, base_url: str) -> None:")
    lines.append(f'    """{case["id"]} {title}"""')
    lines.extend(body)
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser()
    parser.add_argument("case", nargs="?", help="单个用例 JSON")
    parser.add_argument("--all", dest="all_dir", help="目录：批量生成")
    parser.add_argument("--out", default="")
    parser.add_argument("--check", action="store_true", help="只校验生成物是否被手改")
    args = parser.parse_args()

    if args.all_dir:
        directory = Path(args.all_dir)
        files = sorted(directory.glob("*.json"))
        if not files:
            print(f"[render] 目录里没有 JSON：{directory}")
            return 1
        mismatches = 0
        for path in files:
            case = json.loads(path.read_text(encoding="utf-8"))
            try:
                rel_path = path.resolve().relative_to(Path.cwd().resolve()).as_posix()
            except ValueError:
                rel_path = path.name
            content = render_case(case, rel_path)
            target = Path("tests") / f"test_{re.sub(r'[^0-9a-zA-Z]+', '_', case['id']).strip('_').lower()}.py"

            if args.check:
                existing = target.read_text(encoding="utf-8") if target.exists() else None
                if existing is None:
                    print(f"[check] MISSING {target}")
                    mismatches += 1
                elif existing != content:
                    print(f"[check] DIRTY   {target}（被手改过，或改了 case 没重新生成）")
                    mismatches += 1
                else:
                    print(f"[check] ok      {target}")
                continue

            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
            print(f"[render] {path.name} -> {target} ({len(case['steps'])} steps)")

        if args.check:
            if mismatches:
                print(f"\n{mismatches} 个生成物与 spec/cases 不一致——tests/ 只能由 render 产出")
                return 1
            print("\n全部一致：tests/ 没有被手改")
        return 0

    if not args.case:
        print("用法: python tools/render.py <case.json> [--out 文件] | --all <目录> [--check]")
        return 2

    path = Path(args.case)
    case = json.loads(path.read_text(encoding="utf-8"))
    content = render_case(case, path.name)
    target = Path(args.out) if args.out else Path("tests") / f"test_{re.sub(r'[^0-9a-zA-Z]+', '_', case['id']).strip('_').lower()}.py"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    print(f"[render] {path} -> {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
